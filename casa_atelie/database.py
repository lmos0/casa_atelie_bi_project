import re
from pathlib import Path
from sqlalchemy import create_engine, event, text

ROOT = Path(__file__).resolve().parents[1]


def connect(url):
    engine = create_engine(url)
    if engine.dialect.name == 'sqlite':
        @event.listens_for(engine, 'connect')
        def enable_fk(dbapi, _):
            dbapi.execute('PRAGMA foreign_keys=ON')
    return engine


def statement(conn, sql, params=None):
    if conn.dialect.name == 'sqlite':
        sql = sql.replace('dw.', '').replace('bi.', '').replace('staging.', '')
    return conn.execute(text(sql), params or {})


def initialize(engine):
    with engine.begin() as conn:
        
        sql = (ROOT / 'sql/schema.sql').read_text()
        if engine.dialect.name == 'sqlite':
            sql = re.sub(r'CREATE SCHEMA IF NOT EXISTS \w+;', '', sql)
            sql = sql.replace('CREATE OR REPLACE VIEW', 'CREATE VIEW IF NOT EXISTS')
            sql = sql.replace('bigint GENERATED BY DEFAULT AS IDENTITY', 'integer')
        sql = re.sub(r'--[^\n]*', '', sql)
        for command in sql.split(';'):
            if command.strip():
                statement(conn, command)


def clear_database(engine):
    tables = (
        'staging.etl_registro', 'staging.etl_linha', 'staging.etl_lote',
        'dw.fato_pagamento', 'dw.fato_inscricao', 'dw.fato_interesse',
        'dw.fato_oferta_turma', 'dw.dim_participante', 'dw.dim_perfil',
        'dw.dim_oficina', 'dw.dim_turma', 'dw.dim_data', 'dw.dim_status',
        'dw.dim_forma_pagamento', 'dw.dim_origem',
    )
    with engine.begin() as conn:
        for table in tables:
            statement(conn, 'DELETE FROM ' + table)


def row(conn, table, **keys):
    where = ' AND '.join(f'{key}=:{key}' for key in keys)
    return statement(conn, f'SELECT * FROM {table} WHERE {where}', keys).mappings().first()


def insert(conn, table, values, returning=None):
    cols = ','.join(values)
    params = ','.join(':' + key for key in values)
    suffix = f' RETURNING {returning}' if returning else ''
    result = statement(conn, f'INSERT INTO {table} ({cols}) VALUES ({params}){suffix}', values)
    return result.scalar_one() if returning else None


def dimension(conn, table, key, values):
    found = row(conn, 'dw.' + table, **values)
    return found[key] if found else insert(conn, 'dw.' + table, values, key)
