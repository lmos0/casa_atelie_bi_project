CREATE SCHEMA IF NOT EXISTS dw;

CREATE SCHEMA IF NOT EXISTS bi;

CREATE TABLE IF NOT EXISTS dw.dim_data (
  sk_data integer NOT NULL PRIMARY KEY,
  data date NOT NULL UNIQUE,
  ano smallint NOT NULL,
  mes smallint NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_participante (
  sk_participante bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  chave_pseudonima char(64) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS dw.dim_perfil (
  sk_perfil bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  faixa_etaria varchar(20) NOT NULL,
  cidade varchar(100) NOT NULL,
  UNIQUE (faixa_etaria, cidade)
);

CREATE TABLE IF NOT EXISTS dw.dim_oficina (
  sk_oficina bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  id_oficina varchar(40) NOT NULL UNIQUE,
  nome_oficina varchar(100) NOT NULL,
  modalidade varchar(40) NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_turma (
  sk_turma bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  id_turma varchar(40) NOT NULL UNIQUE,
  data_inicio date NOT NULL,
  data_fim date NOT NULL CHECK (data_fim >= data_inicio)
);

CREATE TABLE IF NOT EXISTS dw.dim_status (
  sk_status bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  dominio varchar(20) NOT NULL,
  codigo varchar(30) NOT NULL,
  UNIQUE (dominio, codigo)
);

CREATE TABLE IF NOT EXISTS dw.dim_forma_pagamento (
  sk_forma_pagamento bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  codigo varchar(30) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS dw.dim_origem (
  sk_origem bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  codigo varchar(40) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS dw.fato_interesse (
  id_interesse varchar(40) NOT NULL PRIMARY KEY,
  sk_participante bigint NOT NULL REFERENCES dw.dim_participante(sk_participante),
  sk_oficina bigint NOT NULL REFERENCES dw.dim_oficina(sk_oficina),
  sk_data_interesse integer NOT NULL REFERENCES dw.dim_data(sk_data),
  sk_perfil bigint NOT NULL REFERENCES dw.dim_perfil(sk_perfil),
  sk_status bigint NOT NULL REFERENCES dw.dim_status(sk_status),
  sk_origem bigint NOT NULL REFERENCES dw.dim_origem(sk_origem)
);

CREATE TABLE IF NOT EXISTS dw.fato_inscricao (
  id_inscricao varchar(40) NOT NULL PRIMARY KEY,
  id_interesse varchar(40),
  sk_participante bigint NOT NULL REFERENCES dw.dim_participante(sk_participante),
  sk_oficina bigint NOT NULL REFERENCES dw.dim_oficina(sk_oficina),
  sk_turma bigint NOT NULL REFERENCES dw.dim_turma(sk_turma),
  sk_data_inscricao integer NOT NULL REFERENCES dw.dim_data(sk_data),
  sk_data_confirmacao integer REFERENCES dw.dim_data(sk_data),
  sk_perfil bigint NOT NULL REFERENCES dw.dim_perfil(sk_perfil),
  sk_status bigint NOT NULL REFERENCES dw.dim_status(sk_status),
  valor_contratado numeric(12,2) NOT NULL CHECK (valor_contratado >= 0)
);

CREATE TABLE IF NOT EXISTS dw.fato_pagamento (
  id_pagamento varchar(40) NOT NULL PRIMARY KEY,
  id_inscricao varchar(40) NOT NULL,
  sk_participante bigint NOT NULL REFERENCES dw.dim_participante(sk_participante),
  sk_oficina bigint NOT NULL REFERENCES dw.dim_oficina(sk_oficina),
  sk_turma bigint NOT NULL REFERENCES dw.dim_turma(sk_turma),
  sk_data_pagamento integer NOT NULL REFERENCES dw.dim_data(sk_data),
  sk_status bigint NOT NULL REFERENCES dw.dim_status(sk_status),
  sk_forma_pagamento bigint NOT NULL REFERENCES dw.dim_forma_pagamento(sk_forma_pagamento),
  valor_pago numeric(12,2) NOT NULL CHECK (valor_pago >= 0)
);

CREATE TABLE IF NOT EXISTS dw.fato_oferta_turma (
  sk_turma bigint NOT NULL PRIMARY KEY REFERENCES dw.dim_turma(sk_turma),
  sk_oficina bigint NOT NULL REFERENCES dw.dim_oficina(sk_oficina),
  sk_data_inicio integer NOT NULL REFERENCES dw.dim_data(sk_data),
  sk_status bigint NOT NULL REFERENCES dw.dim_status(sk_status),
  vagas_ofertadas integer NOT NULL CHECK (vagas_ofertadas > 0)
);

CREATE OR REPLACE VIEW bi.v_recebimentos_mensais AS
SELECT d.ano, d.mes, p.sk_oficina, SUM(p.valor_pago) AS recebido_reais
FROM dw.fato_pagamento p
JOIN dw.dim_data d ON d.sk_data=p.sk_data_pagamento
JOIN dw.dim_status s ON s.sk_status=p.sk_status
WHERE s.dominio='pagamento' AND s.codigo='liquidado'
GROUP BY d.ano,d.mes,p.sk_oficina;

CREATE OR REPLACE VIEW bi.v_ocupacao_turma AS
WITH confirmados AS (
 SELECT i.sk_turma, COUNT(*) AS inscritos_confirmados
 FROM dw.fato_inscricao i JOIN dw.dim_status s ON s.sk_status=i.sk_status
 WHERE s.dominio='inscricao' AND s.codigo='confirmada'
 GROUP BY i.sk_turma
)
SELECT o.sk_turma,o.sk_oficina,o.sk_data_inicio,o.vagas_ofertadas,
       COALESCE(c.inscritos_confirmados,0) AS inscritos_confirmados,
       100.0*COALESCE(c.inscritos_confirmados,0)/NULLIF(o.vagas_ofertadas,0) AS ocupacao_pct
FROM dw.fato_oferta_turma o
JOIN dw.dim_status s ON s.sk_status=o.sk_status
LEFT JOIN confirmados c ON c.sk_turma=o.sk_turma
WHERE s.dominio='turma' AND s.codigo='realizada';

CREATE OR REPLACE VIEW bi.v_ocupacao_mensal AS
SELECT d.ano,d.mes,o.sk_oficina,SUM(o.inscritos_confirmados) AS inscritos_confirmados,
       SUM(o.vagas_ofertadas) AS vagas_ofertadas,
       100.0*SUM(o.inscritos_confirmados)/NULLIF(SUM(o.vagas_ofertadas),0) AS ocupacao_pct
FROM bi.v_ocupacao_turma o JOIN dw.dim_data d ON d.sk_data=o.sk_data_inicio
GROUP BY d.ano,d.mes,o.sk_oficina;

CREATE SCHEMA IF NOT EXISTS staging;
CREATE TABLE IF NOT EXISTS staging.etl_lote (
  id_lote varchar(36) PRIMARY KEY,
  criado_em varchar(40) NOT NULL,
  status varchar(20) NOT NULL,
  resumo text NOT NULL
);
CREATE TABLE IF NOT EXISTS staging.etl_linha (
  id_lote varchar(36) NOT NULL REFERENCES staging.etl_lote(id_lote),
  arquivo varchar(255) NOT NULL,
  numero integer NOT NULL,
  tipo varchar(30) NOT NULL,
  conteudo text NOT NULL,
  PRIMARY KEY (id_lote, arquivo, numero)
);
CREATE TABLE IF NOT EXISTS staging.etl_registro (
  tipo varchar(30) NOT NULL,
  chave varchar(40) NOT NULL,
  hash_conteudo char(64) NOT NULL,
  id_lote varchar(36) NOT NULL REFERENCES staging.etl_lote(id_lote),
  PRIMARY KEY (tipo, chave)
);
